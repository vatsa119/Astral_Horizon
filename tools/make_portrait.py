"""Build js/portrait-data.js: a stipple of the portrait for the particle hero.

Usage (from the project root):
  uv run --with "rembg[cpu]" --with pillow --with numpy python tools/make_portrait.py

Browsers block getImageData on file:// images, so the particles are baked into a JS file here.
"""
import base64, json, sys
import numpy as np
from PIL import Image, ImageFilter, ImageOps
from rembg import remove

SRC = "reference/IMG_9231.jpeg"
BOX = (0, 2030, 920, 2780)   # head and shoulders, in source pixels
OUT_JS = "js/portrait-data.js"
N = 18000
WIDTH = 640

im = Image.open(SRC).convert("RGB")
im = ImageOps.exif_transpose(im)
crop = im.crop(BOX)
cut = remove(crop, post_process_mask=True)

cut = cut.resize((WIDTH, round(WIDTH * cut.height / cut.width)), Image.LANCZOS)
a = np.asarray(cut.split()[3], dtype=np.float32) / 255
rgb = cut.convert("RGB")
lum = np.asarray(ImageOps.autocontrast(rgb.convert("L"), cutoff=2), dtype=np.float32) / 255
lum8 = Image.fromarray((lum * 255).astype("uint8"))
local = np.asarray(lum8.filter(ImageFilter.GaussianBlur(18)), dtype=np.float32) / 255
lum = np.clip(0.55 * lum + 0.45 * (lum - local + 0.5), 0, 1)
lum = np.asarray(ImageOps.equalize(Image.fromarray((lum * 255).astype("uint8"))), dtype=np.float32) / 255
h, w = a.shape

# density: brighter areas get more points, silhouette edge gets a rim so the outline reads
edge = np.asarray(Image.fromarray((a * 255).astype("uint8")).filter(ImageFilter.FIND_EDGES), dtype=np.float32) / 255
gx = np.abs(np.gradient(lum, axis=1)); gy = np.abs(np.gradient(lum, axis=0))
detail = np.clip((gx + gy) * 6, 0, 1)
dens = (a > 0.5) * (0.04 + 1.3 * lum ** 2.4 + 1.1 * detail + 1.2 * edge)
dens = dens / dens.sum()

rng = np.random.default_rng(7)
idx = rng.choice(h * w, size=N, replace=False, p=dens.ravel())
ys, xs = np.divmod(idx, w)
xs = xs + rng.random(N) - 0.5
ys = ys + rng.random(N) - 0.5
br = np.clip(lum[ys.astype(int).clip(0, h - 1), xs.astype(int).clip(0, w - 1)] * 255, 0, 255)

X = np.round(xs / w * 65535).astype("<u2")
Y = np.round(ys / h * 65535).astype("<u2")
B = br.astype("u1")
blob = base64.b64encode(X.tobytes() + Y.tobytes() + B.tobytes()).decode()
with open(OUT_JS, "w", encoding="utf-8") as f:
    f.write("/* generated by tools/make_portrait.py, do not edit */\n")
    f.write("VT.PORTRAIT=%s;\n" % json.dumps({"n": N, "aspect": round(w / h, 4), "data": blob}))
print("points", N, "aspect", w / h, "bytes", len(blob))
